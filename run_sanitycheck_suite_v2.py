def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate Cartesian-product sanity sweeps and plot graph-level simulator metrics."
    )
    parser.add_argument(
        "--config",
        type=Path,
        help=(
            "Optional JSON override with keys: base_config, node_defaults, "
            "sweeps, z_metrics, plot_by_parameters."
        ),
    )
    parser.add_argument(
        "--output-prefix",
        default="sanitycheck_sweep",
        help="Output directory for configs, logs, results.csv, and plots.",
    )
    parser.add_argument(
        "--generate-only",
        action="store_true",
        help="Write config/DAG files but do not call simulate.py.",
    )
    parser.add_argument(
        "--stop-on-error",
        action="store_true",
        help="Stop at the first failed simulator run instead of recording a failed row.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    override = load_runner_config(args.config)

    base_config = deep_update(BASE_SIMULATION_CONFIG, override.get("base_config", {}))
    node_defaults = deep_update(NODE_DEFAULTS, override.get("node_defaults", {}))
    sweeps = normalize_sweeps(override.get("sweeps", SWEEPS))
    z_metric_requests = override.get("z_metrics", Z_METRICS)
    plot_by = override.get("plot_by_parameters", PLOT_BY_PARAMETERS)

    output_dir = output_root(args.output_prefix)
    combos = cartesian_product(sweeps)
    generated = generate_experiment_files(combos, base_config, node_defaults, output_dir)
    manifest = pd.DataFrame(
        {
            **{"experiment_id": item["experiment_id"], "N": item["N"]},
            **item["combo"],
            "config_path": str(item["input_path"]),
            "dag_path": str(item["dag_path"]),
        }
        for item in generated
    )
    output_dir.mkdir(parents=True, exist_ok=True)
    manifest.to_csv(output_dir / "generated_configs.csv", index=False)

    print(f"Generated {len(generated)} experiment configurations in {output_dir / 'configs'}")
    if args.generate_only:
        print("Generate-only mode: not running simulate.py.")
        return

    results = run_experiments(generated, output_dir, continue_on_error=not args.stop_on_error)
    results_csv = output_dir / "results.csv"
    results.to_csv(results_csv, index=False)

    if results.empty or not (results.get("status", "failed") == "ok").any():
        print(f"No completed simulator runs. Wrote failure table to {results_csv}")
        return

    available_metrics = available_metric_columns(results[results["status"] == "ok"])
    z_metrics = resolve_metrics(z_metric_requests, available_metrics)
    plot_params = varied_parameters(sweeps, plot_by)
    figures = plot_all(results, z_metrics, plot_params, list(sweeps), output_dir)

    print("\nDone.")
    print(f"Results CSV: {results_csv}")
    print(f"Generated configs CSV: {output_dir / 'generated_configs.csv'}")
    print(f"Plots: {output_dir / 'plots'}")
    print(f"Metrics plotted: {', '.join(z_metrics)}")
    print(f"Input axes plotted: {', '.join(plot_params) if plot_params else '(none)'}")
    print(f"Figures written: {len(figures)}")


if __name__ == "__main__":
    main()
