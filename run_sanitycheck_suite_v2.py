def available_metric_columns(df: pd.DataFrame) -> list[str]:
    metrics = []
    for column in df.columns:
        if column in METADATA_COLUMNS:
            continue
        if column.endswith("_path") or column.endswith("_log"):
            continue
        numeric = pd.to_numeric(df[column], errors="coerce")
        if numeric.notna().any():
            metrics.append(column)
    return metrics


def resolve_metrics(requested_metrics: list[str], available_metrics: list[str]) -> list[str]:
    resolved = []
    missing = []
    for metric in requested_metrics:
        if metric in available_metrics:
            resolved.append(metric)
            continue
        candidates = METRIC_ALIASES.get(metric, [])
        match = next((candidate for candidate in candidates if candidate in available_metrics), None)
        if match:
            resolved.append(match)
        else:
            missing.append(metric)

    if missing:
        available = ", ".join(sorted(available_metrics))
        raise ValueError(
            "Requested z_metrics are not available: "
            f"{', '.join(missing)}. Available numeric metrics: {available}"
        )
    return list(dict.fromkeys(resolved))


def varied_parameters(sweeps: dict[str, list[Any]], plot_by: list[str] | None) -> list[str]:
    if plot_by is not None:
        return [SWEEP_ALIASES.get(name, name) for name in plot_by if SWEEP_ALIASES.get(name, name) != "N"]
    return [
        name
        for name, values in sweeps.items()
        if name != "N" and len({json.dumps(value, sort_keys=True) for value in values}) > 1
    ]


def numeric_column(df: pd.DataFrame, column: str) -> pd.Series:
    return pd.to_numeric(df[column], errors="coerce")


def is_numeric_parameter(df: pd.DataFrame, column: str) -> bool:
    return numeric_column(df, column).notna().all()


def sorted_unique(values: pd.Series, numeric: bool) -> list[Any]:
    clean = values.dropna().unique().tolist()
    if numeric:
        return sorted(clean, key=float)
    return sorted(clean, key=str)


def context_groups(df: pd.DataFrame, param: str, sweep_params: list[str]):
    other_params = [name for name in sweep_params if name not in {"N", param}]
    other_params = [name for name in other_params if name in df.columns and df[name].nunique(dropna=False) > 1]
    if not other_params:
        yield "", df
        return
    for values, group in df.groupby(other_params, dropna=False):
        if not isinstance(values, tuple):
            values = (values,)
        suffix_bits = [
            f"{name}-{compact_value(value)}"
            for name, value in zip(other_params, values)
        ]
        yield "__" + "__".join(suffix_bits), group


def plot_2d(df: pd.DataFrame, metric: str, param: str, output_dir: Path, suffix: str = "") -> Path | None:
    plot_df = df[["N", param, metric]].copy()
    plot_df["N"] = numeric_column(plot_df, "N")
    plot_df[metric] = numeric_column(plot_df, metric)
    plot_df = plot_df.dropna(subset=["N", param, metric])
    if plot_df.empty:
        return None

    numeric_param = is_numeric_parameter(plot_df, param)
    plot_df = (
        plot_df.groupby(["N", param], dropna=False, as_index=False)[metric]
        .mean()
        .sort_values(["N", param])
    )

    fig, ax = plt.subplots(figsize=(9, 5.5))
    for param_value in sorted_unique(plot_df[param], numeric_param):
        curve = plot_df[plot_df[param] == param_value].sort_values("N")
        ax.plot(curve["N"], curve[metric], marker="o", linewidth=1.8, label=f"{param}={param_value}")

    ax.set_xlabel("N")
    ax.set_ylabel(metric)
    ax.grid(True, alpha=0.3)
    ax.legend(title=param, fontsize=8)
    fig.tight_layout()

    output_dir.mkdir(parents=True, exist_ok=True)
    path = output_dir / f"plot_2d_{metric}_vs_N_by_{param}{suffix}.png"
    fig.savefig(path, dpi=170)
    plt.close(fig)
    return path


def plot_3d(df: pd.DataFrame, metric: str, param: str, output_dir: Path, suffix: str = "") -> Path | None:
    plot_df = df[["N", param, metric]].copy()
    plot_df["N"] = numeric_column(plot_df, "N")
    plot_df[metric] = numeric_column(plot_df, metric)
    plot_df = plot_df.dropna(subset=["N", param, metric])
    if plot_df.empty:
        return None

    numeric_param = is_numeric_parameter(plot_df, param)
    plot_df = plot_df.groupby(["N", param], dropna=False, as_index=False)[metric].mean()
    param_values = sorted_unique(plot_df[param], numeric_param)
    param_positions = {value: idx for idx, value in enumerate(param_values)}
    if numeric_param:
        plot_df["_param_x"] = numeric_column(plot_df, param)
    else:
        plot_df["_param_x"] = plot_df[param].map(param_positions)

    fig = plt.figure(figsize=(9, 7))
    ax = fig.add_subplot(111, projection="3d")

    pivot = plot_df.pivot(index="N", columns="_param_x", values=metric).sort_index()
    use_surface = pivot.shape[0] >= 2 and pivot.shape[1] >= 2 and not pivot.isna().all().all()
    if use_surface:
        x_values = pivot.columns.to_list()
        y_values = pivot.index.to_list()
        x_grid, y_grid = np.meshgrid(x_values, y_values)
        ax.plot_surface(x_grid, y_grid, pivot.to_numpy(), cmap="viridis", alpha=0.82, edgecolor="none")
        ax.scatter(plot_df["_param_x"], plot_df["N"], plot_df[metric], color="black", s=22)
    else:
        ax.scatter(plot_df["_param_x"], plot_df["N"], plot_df[metric], s=36)

    ax.set_xlabel(param)
    ax.set_ylabel("N")
    ax.set_zlabel(metric)
    if not numeric_param:
        ax.set_xticks(list(param_positions.values()))
        ax.set_xticklabels([str(value) for value in param_values], rotation=25, ha="right")
    fig.tight_layout()

    output_dir.mkdir(parents=True, exist_ok=True)
    path = output_dir / f"plot_3d_{metric}_N_{param}{suffix}.png"
    fig.savefig(path, dpi=170)
    plt.close(fig)
    return path


def plot_all(
    results: pd.DataFrame,
    z_metrics: list[str],
    plot_params: list[str],
    sweep_params: list[str],
    output_dir: Path,
) -> list[Path]:
    figures: list[Path] = []
    ok = results[results.get("status", "ok") == "ok"].copy()
    for metric in z_metrics:
        for param in plot_params:
            if param not in ok.columns:
                print(f"Skipping plots for unknown sweep parameter: {param}")
                continue
            for suffix, group in context_groups(ok, param, sweep_params):
                fig2d = plot_2d(group, metric, param, output_dir / "plots" / "2d", suffix)
                fig3d = plot_3d(group, metric, param, output_dir / "plots" / "3d", suffix)
                figures.extend(path for path in [fig2d, fig3d] if path is not None)
    return figures


