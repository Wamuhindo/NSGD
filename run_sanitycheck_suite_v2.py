def find_latest_run_dir(experiment_name: str, arrival_rate: Any, log_dir: Path) -> Path:
    pattern = f"{experiment_name}_arr{arrival_rate}_*"
    def modified_time(path: Path) -> float:
        return path.stat().st_mtime

    candidates = sorted(log_dir.glob(pattern), key=modified_time)
    if not candidates:
        raise FileNotFoundError(f"No log directory found for {log_dir / pattern}")
    return candidates[-1]


def load_graph_rows(run_dir: Path) -> pd.DataFrame:
    metrics_path = run_dir / "all_runs_metrics.csv"
    if metrics_path.exists():
        df = pd.read_csv(metrics_path)
        if "level" in df.columns:
            return df[df["level"] == "graph"].copy()
        return df.copy()

    summary_path = run_dir / "all_runs_summary.csv"
    if summary_path.exists():
        return pd.read_csv(summary_path)

    aggregated_path = run_dir / "aggregated_results.json"
    if aggregated_path.exists():
        with aggregated_path.open() as f:
            aggregated = json.load(f)
        rows = []
        for result in aggregated.get("runs", []):
            rows.append({key: value for key, value in result.items() if key != "per_node"})
        return pd.DataFrame(rows)

    raise FileNotFoundError(f"No simulator result file found in {run_dir}")


def run_one_experiment(
    python: Path,
    generated: dict[str, Any],
    output_dir: Path,
    continue_on_error: bool,
) -> pd.DataFrame:
    stdout_dir = output_dir / "logs" / "stdout"
    stdout_dir.mkdir(parents=True, exist_ok=True)
    stdout_path = stdout_dir / f"{generated['experiment_id']}.log"
    config = generated["config"]

    cmd = [
        str(python),
        str(SIMULATE),
        "--input",
        str(generated["input_path"]),
        "--dag",
        str(generated["dag_path"]),
    ]

    print(f"Running {generated['experiment_id']} ...", flush=True)
    try:
        with stdout_path.open("w") as stdout_file:
            subprocess.run(
                cmd,
                cwd=ROOT,
                check=True,
                stdout=stdout_file,
                stderr=subprocess.STDOUT,
            )
        run_dir = find_latest_run_dir(
            config["experiment_name"],
            config["arrival_rate"],
            Path(config["log_dir"]),
        )
        df = load_graph_rows(run_dir)
        df["status"] = "ok"
        df["error"] = ""
        df["run_dir"] = str(run_dir)
    except Exception as exc:
        if not continue_on_error:
            raise
        df = pd.DataFrame([{"status": "failed", "error": str(exc), "run_dir": ""}])

    df["experiment_id"] = generated["experiment_id"]
    df["experiment_name"] = config["experiment_name"]
    df["N"] = generated["N"]
    df["graph"] = generated["graph"]
    df["config_path"] = str(generated["input_path"])
    df["dag_path"] = str(generated["dag_path"])
    df["stdout_log"] = str(stdout_path)
    for key, value in generated["combo"].items():
        df[key] = json.dumps(value) if isinstance(value, (dict, list)) else value
    return df


def run_experiments(
    generated: list[dict[str, Any]],
    output_dir: Path,
    continue_on_error: bool,
) -> pd.DataFrame:
    python = PYTHON if PYTHON.exists() else Path(sys.executable)
    frames = [
        run_one_experiment(python, item, output_dir, continue_on_error)
        for item in generated
    ]
    return pd.concat(frames, ignore_index=True) if frames else pd.DataFrame()


