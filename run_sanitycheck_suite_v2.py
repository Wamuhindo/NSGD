def output_root(output_prefix: str) -> Path:
    path = Path(output_prefix)
    return path if path.is_absolute() else ROOT / path


def deep_update(base: dict[str, Any], override: dict[str, Any]) -> dict[str, Any]:
    result = copy.deepcopy(base)
    for key, value in override.items():
        if isinstance(value, dict) and isinstance(result.get(key), dict):
            result[key] = deep_update(result[key], value)
        else:
            result[key] = copy.deepcopy(value)
    return result


def load_runner_config(path: Path | None) -> dict[str, Any]:
    if path is None:
        return {}
    with path.open() as f:
        return json.load(f)


def scalar_or_list(value: Any) -> list[Any]:
    if value is None:
        return [None]
    return value if isinstance(value, list) else [value]


def normalize_sweeps(raw_sweeps: dict[str, Any]) -> dict[str, list[Any]]:
    normalized: dict[str, list[Any]] = {}
    for raw_name, raw_values in raw_sweeps.items():
        name = SWEEP_ALIASES.get(raw_name, raw_name)
        values = scalar_or_list(raw_values)
        if not values:
            continue
        normalized[name] = values
    if "N" not in normalized:
        normalized["N"] = [3]
    return normalized


def cartesian_product(sweeps: dict[str, list[Any]]) -> list[dict[str, Any]]:
    keys = list(sweeps)
    return [dict(zip(keys, values)) for values in itertools.product(*(sweeps[k] for k in keys))]


def chain_label(n_nodes: int) -> str:
    return "A1" if n_nodes == 1 else "->".join(f"A{i}" for i in range(1, n_nodes + 1))


def build_dag(n_nodes: int) -> dict[str, Any]:
    dag = {}
    for idx in range(1, n_nodes + 1):
        node = f"A{idx}"
        dag[node] = {
            "next": [f"A{idx + 1}"] if idx < n_nodes else [],
            "transition_probability": [1.0] if idx < n_nodes else [],
        }
    return {"DirectedAcyclicGraph": dag}


def rate_from_mean(mean: Any) -> float:
    mean_float = float(mean)
    if mean_float <= 0:
        raise ValueError(f"Mean service time must be positive, got {mean}")
    return 1.0 / mean_float


def configured_rate(base_rate: Any, n_nodes: int, scale_by_n: bool) -> float:
    rate = float(base_rate)
    return rate * n_nodes if scale_by_n else rate


def build_nodes(n_nodes: int, node_defaults: dict[str, Any], combo: dict[str, Any]) -> dict[str, Any]:
    scale_by_n = bool(node_defaults.get("scale_node_rates_by_N", True))
    template = {
        key: copy.deepcopy(value)
        for key, value in node_defaults.items()
        if key != "scale_node_rates_by_N"
    }

    for param, distribution in NODE_RATE_PARAMS.items():
        if param in combo and combo[param] is not None:
            template[distribution]["rate"] = combo[param]

    for param, distribution in NODE_MEAN_PARAMS.items():
        if param in combo and combo[param] is not None:
            template[distribution]["rate"] = rate_from_mean(combo[param])

    nodes = {}
    for idx in range(1, n_nodes + 1):
        node = copy.deepcopy(template)
        for distribution in NODE_RATE_PARAMS.values():
            node[distribution]["rate"] = configured_rate(
                node[distribution]["rate"],
                n_nodes,
                scale_by_n,
            )
        nodes[f"A{idx}"] = node
    return nodes


def compact_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (list, tuple)):
        return "-".join(compact_value(item) for item in value)
    if isinstance(value, dict):
        return "-".join(f"{key}-{compact_value(value[key])}" for key in sorted(value))
    text = str(value)
    return (
        text.replace("/", "_")
        .replace("\\", "_")
        .replace(" ", "")
        .replace(".", "p")
        .replace("-", "m")
        .replace("[", "")
        .replace("]", "")
        .replace(",", "-")
    )


def combo_slug(combo: dict[str, Any]) -> str:
    parts = [f"{key}-{compact_value(combo[key])}" for key in sorted(combo)]
    return "__".join(parts)


def apply_combo_to_config(
    base_config: dict[str, Any],
    node_defaults: dict[str, Any],
    combo: dict[str, Any],
    output_dir: Path,
) -> dict[str, Any]:
    n_nodes = int(combo["N"])
    config = copy.deepcopy(base_config)
    config["arrival_rate"] = combo.get("arrival_rate", config["arrival_rate"])
    config["nodes"] = build_nodes(n_nodes, node_defaults, combo)
    config["log_dir"] = str(output_dir / "logs")
    config["description"] = f"{config.get('description', '').strip()} | {combo_slug(combo)}"
    config["experiment_name"] = f"{config.get('experiment_name', 'sanitycheck')}_{combo_slug(combo)}"

    if "optimization" in combo:
        config["optimization"] = (
            combo["optimization"]
            if isinstance(combo["optimization"], dict)
            else {"type": combo["optimization"]}
        )

    for param in CONFIG_PARAM_NAMES:
        if param not in combo or combo[param] is None:
            continue
        config[param] = combo[param]

    # simulate.py expects absent optional keys to fall back to defaults. Dropping
    # None keeps the generated JSON cleaner and avoids accidental null handling.
    return {key: value for key, value in config.items() if value is not None}


def write_json(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w") as f:
        json.dump(payload, f, indent=2)
        f.write("\n")


def generate_experiment_files(
    combos: list[dict[str, Any]],
    base_config: dict[str, Any],
    node_defaults: dict[str, Any],
    output_dir: Path,
) -> list[dict[str, Any]]:
    generated = []
    for combo in combos:
        n_nodes = int(combo["N"])
        experiment_id = combo_slug(combo)
        config_dir = output_dir / "configs" / experiment_id
        dag_path = config_dir / f"DAG_N{n_nodes:02d}.json"
        input_path = config_dir / f"input_N{n_nodes:02d}.json"
        config = apply_combo_to_config(base_config, node_defaults, combo, output_dir)
        write_json(dag_path, build_dag(n_nodes))
        write_json(input_path, config)
        generated.append(
            {
                "experiment_id": experiment_id,
                "N": n_nodes,
                "graph": chain_label(n_nodes),
                "combo": combo,
                "config": config,
                "input_path": input_path,
                "dag_path": dag_path,
            }
        )
    return generated


